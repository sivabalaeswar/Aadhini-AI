package ai.aadhini.android.ui.theme

/**
 * Typography roles used by the Aadhini presentation layer.
 *
 * These are semantic roles rather than screen-specific styles, so device
 * environments can adapt the actual rendering without duplicating design rules.
 */
object AadhiniTypography {
    const val DisplaySp = 32
    const val HeadlineSp = 24
    const val TitleSp = 20
    const val BodySp = 16
    const val LabelSp = 14
    const val CaptionSp = 12

    const val DisplayLineHeightSp = 38
    const val HeadlineLineHeightSp = 30
    const val TitleLineHeightSp = 26
    const val BodyLineHeightSp = 22
    const val LabelLineHeightSp = 20
    const val CaptionLineHeightSp = 16
}
